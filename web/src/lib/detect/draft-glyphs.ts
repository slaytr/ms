/**
 * `measured` plus a draft for every character it has no template for. A measured glyph always wins:
 * once a letter is harvested from a real frame its draft is dropped, not mixed in.
 */
export function withDrafts(measured: GlyphSet, drafts: GlyphSet = DRAFT_TEXT_GLYPHS): GlyphSet {
  const missing = Object.fromEntries(Object.entries(drafts).filter(([char]) => !(char in measured)));
  return { ...measured, ...missing };
}
