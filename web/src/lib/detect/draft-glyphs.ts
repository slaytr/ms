/**
 * Hand-drawn candidates for text-font letters we have not captured yet, so a character plate or job
 * line with a letter nobody has harvested can still read.
 *
 * These are NOT measured from the game. They are drawn in the style of the harvested glyphs (1px
 * strokes, 13 rows, capitals on rows 1-9, lowercase on rows 3-9, descenders to row 11), several
 * variants per letter because the font is hand-hinted and one pixel can differ. Matching tolerates
 * one wrong pixel, so a near miss still reads. Two safeguards keep this honest:
 *  - a harvested glyph always wins: a letter with any real template never uses its draft
 *    (see withDrafts), so harvesting a real frame replaces the guess;
 *  - draft-glyphs.test.ts rejects a draft that sits within matching range of a different letter.
 *
 * Y and y are cut from the real "yY" glyph. Lowercase l needs no draft (it draws as the capital I bar).
 */

const ROWS = 13;

/** Pads ink rows (starting at row `top`) to the font's full 13-row cell. */
function glyph(top: number, rows: readonly string[]): Bitmap {
  const blank = '.'.repeat(rows[0].length);
  return Array.from({ length: ROWS }, (_, y) => rows[y - top] ?? blank);
}

