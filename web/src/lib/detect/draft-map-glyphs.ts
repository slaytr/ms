import type { Bitmap, GlyphSet } from './types.ts';

/**
 * Hand-drawn candidates for minimap-font characters we have not captured yet, so a map name with a
 * letter nobody has harvested can still read.
 *
 * These are NOT measured from the game. They are drawn in the style of the harvested map glyphs (bold,
 * 2px strokes, a 14-row cell, capitals and digits on rows 3-11, lowercase on rows 5-11, ascenders from
 * row 3, descenders to row 13), with a second variant where the font's hand-hinting could plausibly
 * differ by a pixel. A wrong draft is harmless: it simply never matches and the name stays unread, as
 * it would have without it. Three safeguards keep it that way:
 *  - a harvested glyph always wins: a character with any real template never uses its draft (see
 *    withDrafts), so labelling a real frame and harvesting replaces the guess;
 *  - draft-map-glyphs.test.ts rejects a draft that sits within matching range of a different character;
 *  - a draft that fails that test is left out of this file rather than shipped.
 *
 * Capital I and lowercase l are the same bar in this font, and resolveMapLookalikes tells them apart by
 * position, so l needs no draft. Characters whose natural shape sits within a pixel or two of a real
 * glyph (a period beside the comma, an exclamation mark beside the I) are left out on purpose.
 */

const ROWS = 14;

/** Pads ink rows (starting at row `top`) to the font's full 14-row cell. */
function glyph(top: number, rows: readonly string[]): Bitmap {
  const blank = '.'.repeat(rows[0].length);
  return Array.from({ length: ROWS }, (_, y) => rows[y - top] ?? blank);
}

/** Capitals and digits: nine rows, rows 3-11. */
const cap = (rows: readonly string[]) => glyph(3, rows);
/** Lowercase with no ascender or descender: seven rows, rows 5-11. */
const low = (rows: readonly string[]) => glyph(5, rows);
/** Lowercase with a descender: rows 5-13. */
const desc = (rows: readonly string[]) => glyph(5, rows);
/** Lowercase with an ascender: rows 3-11. */
const tall = (rows: readonly string[]) => glyph(3, rows);

